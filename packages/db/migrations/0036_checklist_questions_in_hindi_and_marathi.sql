-- =============================================================================
-- 0036 — Checklist questions in Hindi and Marathi
--
-- The auditors who walk a plant are not all at ease in English, so the field app can show
-- each question in Hindi or Marathi, with the English beneath it.
--
-- A translation is **display text, never the record.** The English question is what was
-- published, what the audit answered, what the report prints and what a corrective action
-- quotes. Nothing that scores, reports or is signed reads this table.
--
-- Why a table of its own, keyed by the English sentence rather than by question id:
--
--   * CV-1 makes a published question immutable, and rightly — so a translation cannot be a
--     column on `checklist_question` without bending that trigger for text that is not the
--     record. Beside it, the rule stays exactly as strict as it was.
--   * Re-importing a department makes a new version with new question ids. Keyed by the
--     sentence, every question whose English did not change keeps its translation with no
--     one re-entering it; a question whose English did change has no translation until
--     one is written, and shows in English — never a translation of the old wording.
--   * The key is the text as stored: R-7b's normalized form (whitespace collapsed, quotes
--     straightened, dashes kept), which is what the importer writes.
--
-- A translation may be corrected in place (UPDATE), because improving the Hindi does not
-- change what anybody answered. It is never deleted (D8): no DELETE grant.
--
-- The rows below translate the 443 distinct questions of the department workbook
-- (docs/requirements/5S_lean_audit_data_1.xlsx, nine sheets). They were translated per
-- sheet, in the context of that department — not word for word — keeping the shop-floor
-- words operators actually use (FIFO, WIP, SOP, PPE, pallet, rack, kaizen, red-tag).
-- A question with no row here is shown in English.
-- =============================================================================

CREATE TABLE checklist_question_translation (
  -- `checklist_question.text`, exactly as stored.
  source_text text NOT NULL,
  -- English is the source, so it is not a translation of itself.
  language    text NOT NULL CHECK (language IN ('hi','mr')),
  text        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (source_text, language),
  CONSTRAINT checklist_question_translation_source_length
    CHECK (char_length(source_text) BETWEEN 1 AND 500),
  -- Devanagari runs longer than the English it renders; twice the question's cap.
  CONSTRAINT checklist_question_translation_text_length
    CHECK (char_length(text) BETWEEN 1 AND 1000)
);

CREATE TRIGGER checklist_question_translation_set_updated_at
  BEFORE UPDATE ON checklist_question_translation
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE checklist_question_translation ENABLE ROW LEVEL SECURITY;

-- Read exactly as broadly as the questions themselves (D2): every device caches them.
CREATE POLICY checklist_question_translation_select ON checklist_question_translation
  FOR SELECT USING (app_actor_id() IS NOT NULL);
CREATE POLICY checklist_question_translation_insert ON checklist_question_translation
  FOR INSERT WITH CHECK (app_is_super_admin());
CREATE POLICY checklist_question_translation_update ON checklist_question_translation
  FOR UPDATE USING (app_is_super_admin());

GRANT SELECT, INSERT, UPDATE ON checklist_question_translation TO audit5s_app;

